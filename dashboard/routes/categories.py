@router.get("/list", response_model=CategoryListResponse, summary="List all product categories")
def list_categories(
    query: Optional[str] = Query(None, description="Search by category name"),
    limit: int = Query(100, ge=1, le=1000, description="Pagination limit"),
    offset: int = Query(0, ge=0, description="Pagination offset"),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Lists all product categories with product count metrics."""
    try:
        logger.info(f"[Categories] User '{current_user.username}' requested category list")
        q = db.query(models.Category)
        
        if query:
            q = q.filter(models.Category.name.ilike(f"%{query.strip()}%"))

        total_count = q.count()
        cats = q.order_by(models.Category.name.asc()).offset(offset).limit(limit).all()

        items = []
        for c in cats:
            p_count = db.query(models.Product).filter(models.Product.category_id == c.id, models.Product.is_active == 1).count()
            items.append(CategoryListItem(
                id=c.id,
                name=c.name,
                description=c.description,
                product_count=p_count
            ))

        return CategoryListResponse(categories=items, count=total_count)
    except Exception as e:
        logger.error(f"[Categories Error] Failed to list categories: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error fetching categories list: {str(e)}"
        )


@router.get("/details/{category_id}", response_model=CategoryDetailsResponse, summary="Get details for single category")
def get_category_details(
    category_id: int,
    preset: Optional[str] = Query(None),
    start_date: Optional[str] = Query(None),
    end_date: Optional[str] = Query(None),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Retrieves detailed performance metrics for a specific product category."""
    try:
        _validate_date_inputs(preset, start_date, end_date)
        start, end = resolve_date_range(start_date, end_date, preset or "this_month")
        
        cat = db.query(models.Category).filter(models.Category.id == category_id).first()
        if not cat:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Category ID {category_id} not found")

        raw_contribs = category_service.get_category_contributions(db, start, end)
        target = next((c for c in raw_contribs if c.get("category_id") == category_id), None)
        
        total_rev = target.get("total_revenue", 0.0) if target else 0.0
        pct = target.get("percentage", 0.0) if target else 0.0
        qty = target.get("total_qty_sold", 0.0) if target else 0.0

        p_count = db.query(models.Product).filter(models.Product.category_id == category_id, models.Product.is_active == 1).count()
        
        # Find top selling product in category
        sold_rows = db.query(
            models.Product.id,
            models.Product.name,
            func.sum(models.SaleItem.qty).label("qty"),
        ).join(models.SaleItem).join(models.Sale).filter(
            models.Product.category_id == category_id,
            models.Sale.status.in_(POSTED_SALE_STATUSES),
            func.date(models.Sale.created_at) >= start,
            func.date(models.Sale.created_at) <= end,
        ).group_by(models.Product.id, models.Product.name).all()
        returned_rows = db.query(
            models.SaleReturnItem.product_id,
            func.sum(models.SaleReturnItem.qty).label("qty"),
        ).join(models.SaleReturn).join(
            models.Product, models.Product.id == models.SaleReturnItem.product_id
        ).filter(
            models.Product.category_id == category_id,
            func.date(models.SaleReturn.posted_at) >= start,
            func.date(models.SaleReturn.posted_at) <= end,
        ).group_by(models.SaleReturnItem.product_id).all()
        returned_map = {row.product_id: float(row.qty or 0) for row in returned_rows}
        top_prod = max(
            sold_rows,
            key=lambda row: float(row.qty or 0) - returned_map.get(row.id, 0.0),
            default=None,
        )
        top_p_name = top_prod.name if top_prod else None

        return CategoryDetailsResponse(
            category_id=cat.id,
            category_name=cat.name,
            period_start=start,
            period_end=end,
            total_revenue=total_rev,
            contribution_percentage=pct,
            total_qty_sold=qty,
            product_count=p_count,
            top_product_name=top_p_name
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"[Categories Error] Failed to get category details for ID {category_id}: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error getting category details: {str(e)}"
        )


@router.get("/top-bottom", response_model=TopBottomCategoryResponse, summary="Get top and bottom performing categories")
def top_bottom_categories(
    preset: Optional[str] = Query(None),
    start_date: Optional[str] = Query(None),
    end_date: Optional[str] = Query(None),
    top_n: int = Query(5, ge=1, le=20),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Returns top N and bottom N performing categories by revenue contribution."""
    try:
        _validate_date_inputs(preset, start_date, end_date)
        start, end = resolve_date_range(start_date, end_date, preset or "this_month")
        
        raw_contribs = category_service.get_category_contributions(db, start, end)
        sorted_contribs = sorted(raw_contribs, key=lambda x: x.get("total_revenue", 0.0), reverse=True)

        top_items = [CategoryContributionItem(**item) for item in sorted_contribs[:top_n]]
        bottom_items = [CategoryContributionItem(**item) for item in sorted_contribs[-top_n:]]

        return TopBottomCategoryResponse(
            top_categories=top_items,
            bottom_categories=bottom_items
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"[Categories Error] Failed to calculate top/bottom categories: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error calculating top/bottom categories: {str(e)}"
        )


@router.get("/export", summary="Export category performance report as CSV")
def export_category_report(
    preset: Optional[str] = Query(None),
    start_date: Optional[str] = Query(None),
    end_date: Optional[str] = Query(None),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Generates and downloads a CSV export of category revenue contributions."""
    try:
        _validate_date_inputs(preset, start_date, end_date)
        start, end = resolve_date_range(start_date, end_date, preset or "this_month")
        
        raw_contribs = category_service.get_category_contributions(db, start, end)

        output = io.StringIO()
        writer = csv.writer(output)
        
        # Write CSV Header
        writer.writerow(["Category ID", "Category Name", "Total Revenue (PKR)", "Contribution %", "Total Quantity Sold"])
        
        for c in raw_contribs:
            writer.writerow([
                c.get("category_id", ""),
                c.get("category_name", ""),
                f"{c.get('total_revenue', 0.0):.2f}",
                f"{c.get('percentage', 0.0):.1f}%",
                f"{c.get('total_qty_sold', 0.0):.2f}"
            ])

        output.seek(0)
        filename = f"category_performance_{start}_to_{end}.csv"
        
        return Response(
            content=output.getvalue(),
            media_type="text/csv",
            headers={"Content-Disposition": f"attachment; filename={filename}"}
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"[Categories Error] Failed to export CSV: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error exporting category report CSV: {str(e)}"
        )
