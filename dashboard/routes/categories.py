router = APIRouter()

ALLOWED_PRESETS = {"today", "yesterday", "this_week", "last_week", "this_month", "last_month", "last7", "last30", "this_year", "custom"}


# ── Pydantic Schemas ──────────────────────────────────────────────────────────
class CategoryContributionItem(BaseModel):
    category_id: Optional[int] = Field(None, description="Category database ID")
    category_name: str = Field(..., description="Category name")
    total_revenue: float = Field(0.0, description="Total gross revenue generated by category")
    percentage: float = Field(0.0, description="Revenue contribution percentage of total")
    total_qty_sold: float = Field(0.0, description="Total quantity of items sold in category")


class CategoryTrendSeries(BaseModel):
    category_name: str = Field(..., description="Category name")
    data: List[float] = Field(default_factory=list, description="Revenue data points over time")


class CategoryTrendResponse(BaseModel):
    labels: List[str] = Field(default_factory=list, description="Time labels (days or months)")
    series: List[CategoryTrendSeries] = Field(default_factory=list, description="Series per category")


class CategoryListItem(BaseModel):
    id: int
    name: str
    description: Optional[str] = None
    product_count: int = 0


class CategoryListResponse(BaseModel):
    categories: List[CategoryListItem]
    count: int


class CategoryDetailsResponse(BaseModel):
    category_id: int
    category_name: str
    period_start: str
    period_end: str
    total_revenue: float
    contribution_percentage: float
    total_qty_sold: float
    product_count: int
    top_product_name: Optional[str] = None


class CategoryComparisonItem(BaseModel):
    category_id: Optional[int]
    category_name: str
    revenue: float
    contribution_pct: float
    order_items_count: int


class CategoryComparisonResponse(BaseModel):
    period_start: str
    period_end: str
    total_category_revenue: float
    categories: List[CategoryComparisonItem]


class TopBottomCategoryResponse(BaseModel):
    top_categories: List[CategoryContributionItem]
    bottom_categories: List[CategoryContributionItem]


class HealthCheckResponse(BaseModel):
    status: str
    module: str
    timestamp: str


# ── Helper Functions ──────────────────────────────────────────────────────────
def _validate_date_inputs(preset: Optional[str], start_date: Optional[str], end_date: Optional[str]):
    if preset and preset.lower() not in ALLOWED_PRESETS:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Invalid preset '{preset}'. Allowed presets: {', '.join(sorted(ALLOWED_PRESETS))}"
        )
    if start_date and isinstance(start_date, str):
        try:
            date.fromisoformat(start_date)
        except (ValueError, TypeError):
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"Invalid start_date '{start_date}'. Must be YYYY-MM-DD format."
            )
    if end_date and isinstance(end_date, str):
        try:
            date.fromisoformat(end_date)
        except (ValueError, TypeError):
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"Invalid end_date '{end_date}'. Must be YYYY-MM-DD format."
            )


# ── Endpoints ─────────────────────────────────────────────────────────────────

@router.get("/health", response_model=HealthCheckResponse, summary="Categories module health check")
def categories_health():
    """Health check endpoint for the categories module."""
    return HealthCheckResponse(
        status="ok",
        module="categories",
        timestamp=datetime.now(timezone.utc).isoformat()
    )


@router.get("/contributions", response_model=List[CategoryContributionItem], summary="Get revenue contribution by category")
def category_contributions(
    preset: Optional[str] = Query(None, description="Date preset filter: this_month, last30, etc."),
    start_date: Optional[str] = Query(None, description="Start date YYYY-MM-DD"),
    end_date: Optional[str] = Query(None, description="End date YYYY-MM-DD"),
    category_name: Optional[str] = Query(None, description="Filter by specific category name"),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """
    Retrieves revenue contribution and quantity sold grouped by product category.
    Fully preserves payload array format expected by desktop UI.
    """
    try:
        _validate_date_inputs(preset, start_date, end_date)
        start, end = resolve_date_range(start_date, end_date, preset or "this_month")
        logger.info(f"[Categories] User '{current_user.username}' requested contributions for period {start} to {end}")
        
        raw = category_service.get_category_contributions(db, start, end)
        
        if category_name:
            c_lower = category_name.lower().strip()
            raw = [c for c in raw if c_lower in str(c.get("category_name", "")).lower()]

        items = [CategoryContributionItem(**item) for item in raw]
        return items
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"[Categories Error] Failed to calculate category contributions: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error calculating category contributions: {str(e)}"
        )


